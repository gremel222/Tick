export const COURSE = [...CORE_MODULES, ...EXTRA_MODULES];

/* ─────────────────────── утилиты курса ─────────────────────── */

export const allLessons = () => COURSE.flatMap((m) => m.lessons.map((l) => ({ module: m, lesson: l })));

export function moduleProgress(m) {
  const total = m.lessons.length;
  const done = m.lessons.filter((l) => store.lessonState(l.id).done).length;
  return { done, total, pct: total ? Math.round((done / total) * 100) : 0 };
}

export function nextLesson() {
  for (const m of COURSE) {
    for (const l of m.lessons) {
      const st = store.lessonState(l.id);
      if (!st.done) return { module: m, lesson: l };
    }
  }
  return null;
}

export function findLessonById(moduleId, lessonId) {
  const m = COURSE.find((x) => x.id === moduleId);
  if (!m) return null;
  const l = m.lessons.find((x) => x.id === lessonId);
  return l ? { module: m, lesson: l } : null;
}

/** Урок, который ссылается на страницу справочника (для кнопки «Пройти урок по теме»). */
export function findLessonForDoc(docId) {
  if (!docId) return null;
  const norm = String(docId).replace(/\/index$/, '');
  for (const m of COURSE) {
    for (const l of m.lessons) {
      for (const r of l.refs || []) {
        if (r.id === docId || r.id.replace(/\/index$/, '') === norm || norm.startsWith(r.id + '/') || r.id.startsWith(norm + '/')) {
          return { module: m, lesson: l };
        }
      }
    }
  }
  return null;
}
